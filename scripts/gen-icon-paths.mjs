// Downloads the Lucide (ISC) icon nodes for every name used in
// src/domain/iconPack.ts and writes them as inline SVG markup to
// src/icons/paths.ts. Run after adding/renaming pack entries:
//   node scripts/gen-icon-paths.mjs
import { execFileSync } from 'node:child_process'
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const LUCIDE_VERSION = '0.469.0'
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const packFile = resolve(root, 'src/domain/iconPack.ts')

const pack = readFileSync(packFile, 'utf8')
const raw = pack.split('RAW_ICON_PACK = `')[1]?.split('`')[0]
if (!raw) throw new Error(`RAW_ICON_PACK not found in ${packFile}`)

const names = raw
  .split('\n')
  .map((line) => line.trim())
  .filter((line) => line && !line.startsWith('#'))
  .map((line) => line.split(/\s+/)[0])

const dupes = names.filter((name, i) => names.indexOf(name) !== i)
if (dupes.length) throw new Error(`duplicate icon names: ${[...new Set(dupes)].join(', ')}`)

const res = await fetch(`https://unpkg.com/lucide-static@${LUCIDE_VERSION}/icon-nodes.json`)
if (!res.ok) throw new Error(`failed to fetch Lucide icons: ${res.status}`)
const nodes = await res.json()

const missing = names.filter((name) => !nodes[name])
if (missing.length) throw new Error(`unknown Lucide icons: ${missing.join(', ')}`)

const escapeAttr = (value) =>
  String(value).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/"/g, '&quot;')

function serialize(node) {
  const [tag, attrs] = node
  const pairs = Object.entries(attrs ?? {})
    .map(([key, value]) => ` ${key.toLowerCase()}="${escapeAttr(value)}"`)
    .join('')
  return `<${tag}${pairs} />`
}

const entries = names.map((name) => {
  const markup = nodes[name].map(serialize).join('')
  return `  '${name}': '${markup.replace(/'/g, "\\'")}',`
})

const out = `// Generated by scripts/gen-icon-paths.mjs from lucide-static ${LUCIDE_VERSION}.
// Lucide is licensed under the ISC license: https://lucide.dev/license
// Do not edit manually — rerun the script after changing the icon pack.

export const ICON_PATHS: Record<string, string> = {
${entries.join('\n')}
}
`

mkdirSync(resolve(root, 'src/icons'), { recursive: true })
const outFile = resolve(root, 'src/icons/paths.ts')
writeFileSync(outFile, out)
// Keep the generated file identical to what `pnpm lint` expects.
execFileSync('pnpm', ['exec', 'biome', 'format', '--write', outFile], {
  cwd: root,
  stdio: 'ignore',
})
console.log(`wrote ${names.length} icons to src/icons/paths.ts`)
